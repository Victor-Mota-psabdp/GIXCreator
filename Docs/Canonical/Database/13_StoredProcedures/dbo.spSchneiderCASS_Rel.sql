	,ITF.dc
	,ITF.CD_TP_MOEDA
	,ITF.VLR_ORG
	,ITF.VLR_RS
	,ITF.PARIDADE
	into tmp_Rel_SCHCASS_INVOICE
	FROM Fatura FAT (NOLOCK)
	INNER JOIN Item_fat ITF (nolock)
		ON FAT.FatCod = ITF.FatCod
	WHERE num_proc like '%SCH%'
	and FAT.fatstatus <> 0 -- Não envia as canceladas
	and FAT.FatDtEmissao between @DtInicial and @DtFinal
	and FAT.FatCod like @FatCod

	
-- TABELA DETALHE - INVOICE
	SELECT DISTINCT
	NUM_PROC
	,FATCOD
	,convert(varchar, FATDTEMISSAO, 112)	AS FATDTEMISSAO
	,convert(varchar, fatdtvenc, 112)		AS FATDTVENC
	,CONVERT(VARCHAR(3),NULL)				AS CURR_CONVERT_1
	,CONVERT(FLOAT,NULL)					AS CURR_EXCHANGE_1
	,CONVERT(VARCHAR(3),NULL)				AS CURR_CONVERT_2
	,CONVERT(FLOAT,NULL)					AS CURR_EXCHANGE_2
	INTO tmp_Rel_SCHCASS_INVOICE_TRATADO
	FROM tmp_Rel_SCHCASS_INVOICE

	SELECT 
	FATCOD
	,MIN(PARIDADE)				AS PARIDADE_01
	,CONVERT(VARCHAR(3),NULL)	AS MOEDA_PARIDADE_01
	,MAX(PARIDADE)				AS PARIDADE_02
	,CONVERT(VARCHAR(3),NULL)	AS MOEDA_PARIDADE_02
	,	(SELECT COUNT(DISTINCT CD_TP_MOEDA)
		FROM tmp_Rel_SCHCASS_INVOICE TMP2
		WHERE TMP1.FATCOD = TMP2.FATCOD
		) AS QTD_PARIDADE
	into tmp_Rel_SCHCASS_INVOICE_PARIDADES
	FROM tmp_Rel_SCHCASS_INVOICE TMP1
	--WHERE FATCOD = 'IASCH202010001BRA'
	GROUP BY FATCOD

	UPDATE tmp_Rel_SCHCASS_INVOICE_PARIDADES
	SET 
	MOEDA_PARIDADE_01 = 
							(SELECT TOP 1 CD_TP_MOEDA 
							FROM tmp_Rel_SCHCASS_INVOICE P2 
							WHERE P2.FATCOD = P.FATCOD 
							AND P2.PARIDADE = PARIDADE_01) 
	,MOEDA_PARIDADE_02 = 
							(SELECT TOP 1 CD_TP_MOEDA 
							FROM tmp_Rel_SCHCASS_INVOICE P3
							WHERE P3.FATCOD = P.FATCOD 
							AND P3.PARIDADE = PARIDADE_02) 
	FROM tmp_Rel_SCHCASS_INVOICE_PARIDADES P



	UPDATE tmp_Rel_SCHCASS_INVOICE_TRATADO
	SET CURR_CONVERT_1 = MOEDA_PARIDADE_01
	,CURR_EXCHANGE_1 = PARIDADE_01
	FROM tmp_Rel_SCHCASS_INVOICE_TRATADO T
	INNER JOIN tmp_Rel_SCHCASS_INVOICE_PARIDADES P
