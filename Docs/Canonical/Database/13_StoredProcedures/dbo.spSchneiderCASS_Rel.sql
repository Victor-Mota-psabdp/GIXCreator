	declare @HSGSeq  int=null
	Declare @FATCOD_CUR	varchar(17) 
	declare @idItemFat bigint


	Declare Cur_invoice_seq cursor for 
	select FATCOD, idItemFat from @Tab_Invoice_Seq
	
	open Cur_invoice_seq
		Fetch Next From Cur_invoice_seq Into @FATCOD_CUR,@idItemFat
		While @@FETCH_STATUS = 0
		Begin
			Set @HSGSeq = IsNull((Select Max(Invoice_Seq) From tmp_Rel_SCHCASS_INVOICE Where fatCod = @FATCOD_CUR),0) + 1 
			
			update tmp_Rel_SCHCASS_INVOICE set Invoice_Seq = @HSGSeq
			where FATCOD= @FATCOD_CUR
			and	idItemFat=@idItemFat
			
			Fetch Next From Cur_invoice_seq Into @FATCOD_CUR,@idItemFat
		end
	close Cur_invoice_seq
	deallocate Cur_invoice_seq 

	DELETE from @Tab_Invoice_Seq

